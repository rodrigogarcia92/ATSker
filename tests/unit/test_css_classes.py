"""Every class a template uses exists in the committed Tailwind build (A.9.1).

`src/web/static/app.css` is generated by `npm run build:css` and committed, because the
container serves it without a Node build. F2.8 added the "Eliminar todo" link with
`bg-red-700 … hover:bg-red-600` and nobody rebuilt: it rendered as white text on no
background, and so does any class added since the last build. This test is the reminder
the build step cannot give.
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TEMPLATES = ROOT / "src" / "web" / "templates"
STYLESHEET = ROOT / "src" / "web" / "static" / "app.css"

# What a template's `class` attribute holds: plain tokens, and Jinja that builds one.
# The latter is an expression, not a class name, so a token carrying a delimiter is
# ignored. `%}`/`}}` matter as much as the openers: `{% if x %}bg-emerald-50{% endif %}`
# splits into `%}bg-emerald-50`, `{%` and `endif`, and a closing tag glued to a class
# name is exactly the case this filter exists for.
CLASS_ATTRIBUTE = re.compile(r'class="([^"]*)"')
JINJA = ("{{", "{%", "}}", "%}")

# A bare utility like `flex` carries no dash, so the words Tailwind emits without one
# are named; any other bare word is a class this test has no opinion about.
BARE_UTILITIES = {
    "block",
    "border",
    "flex",
    "grid",
    "hidden",
    "inline",
    "italic",
    "rounded",
    "underline",
    "uppercase",
}


def class_tokens() -> set[str]:
    """Every Tailwind-looking token in a template's `class` attribute."""
    tokens: set[str] = set()
    for path in sorted(TEMPLATES.rglob("*.html")):
        for attribute in CLASS_ATTRIBUTE.findall(path.read_text(encoding="utf-8")):
            for token in attribute.split():
                if any(marker in token for marker in JINJA):
                    continue
                if "-" in token or token in BARE_UTILITIES:
                    tokens.add(token)
    return tokens


def selector(token: str) -> str:
    """The class selector Tailwind writes for a token — `hover:bg-red-600` is escaped.

    Tailwind escapes the arbitrary-value punctuation too, so `grid-cols-[minmax(0,45fr)]`
    is written `.grid-cols-\\[minmax\\(0\\,45fr\\)\\]`; the commas and parentheses are part
    of the class name the browser matches, not of the selector grammar.
    """
    escaped = token
    for char in ":/.[](),":
        escaped = escaped.replace(char, f"\\{char}")
    return f".{escaped}"


def test_every_class_a_template_uses_is_in_the_committed_build():
    css = STYLESHEET.read_text(encoding="utf-8")
    missing = sorted(
        token
        for token in class_tokens()
        # The class name has to end where a class selector ends: `{` for its own rule,
        # `,`/`:`/`>`/`~`/`+` for a longer one. Without that, `bg-red-70` would be
        # found inside `bg-red-700`.
        if not re.search(re.escape(selector(token)) + r"(?=[{,:>\s~+]|$)", css)
    )

    assert not missing, (
        "these classes are in the templates but not in src/web/static/app.css, so they "
        f"render unstyled: {', '.join(missing)} — run `npm run build:css`"
    )
