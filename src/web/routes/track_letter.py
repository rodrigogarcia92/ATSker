"""A track's one cover-letter template: its page, its save, its "Usar esta" (PRD F8).

The template is presentation + achievements, in the track's language. It is edited here
and listed on Cartas. "Autogenerar" is the one paid call: it fills the two fields and
stores nothing; saving is the user's own text. The owner comes from the session: another
profile's track is a 404 on every route, and so is another profile's template id.
"""

from typing import Annotated

from fastapi import APIRouter, Form, HTTPException, Request
from fastapi.responses import RedirectResponse

from src.extract.client import (
    CallOptions,
    NoModelConfigured,
    ProviderUnavailable,
    StructuredOutputError,
    model_configured,
)
from src.extract.generation import generate_letter_blocks
from src.generate.letters import block_material, check_blocks, voice_notes_for
from src.i18n import t
from src.letters import (
    save_track_template,
    template_status,
    track_template,
    track_templates,
    use_template_for_track,
)
from src.tracks import get_track
from src.web.deps import DbSession, OwnProfile, SignedInUser
from src.web.templating import render

router = APIRouter()


def letter_page(
    request: Request,
    user,
    profile,
    session,
    track,
    *,
    chosen: bool = False,
    values: dict[str, str] | None = None,
    previous: dict[str, str] | None = None,
    violations: list | None = None,
    cost: str | None = None,
    error: str | None = None,
):
    """The track's letter form. `values` pre-fills the two fields when they are not the
    stored ones (an autogenerated draft, which `previous` can restore, with its
    violations and cost)."""
    template = track_template(profile.id, session, track)
    return render(
        request,
        "tracks/letter.html",
        user=user,
        profile=profile,
        track=track,
        letter_template=template,
        linked_templates=track_templates(profile.id, session, track),
        status=template_status(profile.id, session, track),
        chosen=chosen,
        previous=previous,
        all_violations=violations or [],
        cost=cost,
        error=error,
        can_autogenerate=model_configured(),
        values=values
        or {
            "presentation": template.presentation if template else "",
            "achievements": template.achievements if template else "",
        },
    )


@router.get("/tracks/{track_id}/letter")
def track_letter(
    track_id: str,
    request: Request,
    user: SignedInUser,
    session: DbSession,
    profile: OwnProfile,
    chosen: str | None = None,
):
    """The form. A GET never calls the provider."""
    track = get_track(profile.id, session, track_id)
    if track is None:
        return render(request, "not_found.html", user=user, status_code=404)
    return letter_page(request, user, profile, session, track, chosen=chosen == "1")


@router.post("/tracks/{track_id}/letter")
def track_letter_save(
    track_id: str,
    session: DbSession,
    profile: OwnProfile,
    presentation: Annotated[str, Form()] = "",
    achievements: Annotated[str, Form()] = "",
):
    """Save the track's template: create it once, then update that same row (F8)."""
    track = get_track(profile.id, session, track_id)
    if track is None:
        raise HTTPException(status_code=404)
    save_track_template(
        profile.id, session, track, presentation=presentation, achievements=achievements
    )
    session.commit()
    return RedirectResponse(f"/letters?notice=saved&track={track.id}", status_code=303)


@router.post("/tracks/{track_id}/letter/use")
def track_letter_use(
    track_id: str,
    session: DbSession,
    profile: OwnProfile,
    template_id: Annotated[str, Form()],
):
    """"Usar esta": keep this template linked, unlink the others — never delete (F8)."""
    track = get_track(profile.id, session, track_id)
    if track is None:
        raise HTTPException(status_code=404)
    if use_template_for_track(profile.id, session, template_id, track) is None:
        raise HTTPException(status_code=404)
    session.commit()
    return RedirectResponse(f"/tracks/{track.id}/letter?chosen=1", status_code=303)


@router.post("/tracks/{track_id}/letter/autogenerate")
def track_letter_autogenerate(
    track_id: str,
    request: Request,
    user: SignedInUser,
    session: DbSession,
    profile: OwnProfile,
    presentation: Annotated[str, Form()] = "",
    achievements: Annotated[str, Form()] = "",
):
    """One paid call: draft both paragraphs from the track's own material (F8, N8.3).

    The draft fills the two fields and nothing is stored; "Guardar" saves whatever the
    user leaves there, and that text is not re-validated. The track's material is used
    whether or not the track is active.
    """
    track = get_track(profile.id, session, track_id)
    if track is None:
        raise HTTPException(status_code=404)
    current = {"presentation": presentation, "achievements": achievements}
    if not model_configured():
        return letter_page(
            request, user, profile, session, track, values=current,
            error=t("analyze.no_model", user.ui_lang),
        )

    # Everything the prompt reads is computed first; the reads end before the call.
    material, sources = block_material(profile.id, session, track, track.lang)
    voice_notes = voice_notes_for(profile.id, session, track.lang)
    session.commit()
    try:
        proposal = generate_letter_blocks(
            session,
            bullets=material["bullets"],
            roles=material["roles"],
            summary=material["summary"],
            stories=material["stories"],
            voice_notes=voice_notes,
            language=track.lang,
            options=CallOptions(profile_id=profile.id),
        )
    except (NoModelConfigured, ProviderUnavailable, StructuredOutputError):
        session.commit()
        return letter_page(
            request, user, profile, session, track, values=current,
            error=t("generate.failed", user.ui_lang),
        )
    session.commit()

    output = proposal.output
    return letter_page(
        request,
        user,
        profile,
        session,
        track,
        values={
            "presentation": output["presentation"]["text"],
            "achievements": output["achievements"]["text"],
        },
        # What the fields held, so "Deshacer" can put it back without any storage.
        previous=current if any(value.strip() for value in current.values()) else None,
        violations=check_blocks(output, sources),
        cost=f"{proposal.completion.cost_usd}",
    )
